/* Fields unused by an action are the actual zero-valued serialized slots,
 * not extra padding records. The dispatcher stops on the type-zero record. */
#define O101_EVENT(t, action, group, key, a, b, p0, p1, seconds) \
    {(t), (action), (group), (key), (a), (b), {(p0)}, {(p1)}, {(seconds)}}
#define O101_PAIR(t, group, x, y, seconds) \
    O101_EVENT(t, O101_EVENT_PAIR, group, 0, x, y, 0.0f, 0.0f, seconds)
#define O101_ACTIVATE(t, group) \
    O101_EVENT(t, O101_EVENT_ACTIVATE, group, 0, 0, 0, 0.0f, 0.0f, 0.0f)
#define O101_ADVANCE(t, group) \
    O101_EVENT(t, O101_EVENT_ADVANCE, group, 0, 0, 0, 0.0f, 0.0f, 0.0f)
#define O101_PROMOTE(t, group) \
    O101_EVENT(t, O101_EVENT_PROMOTE, group, 0, 0, 0, 0.0f, 0.0f, 0.0f)
#define O101_BYTE17(t, group, value, seconds) \
    O101_EVENT(t, O101_EVENT_BYTE17, group, 0, value, 0, 0.0f, 0.0f, seconds)
#define O101_BYTE16(t, group, value, seconds) \
    O101_EVENT(t, O101_EVENT_BYTE16, group, 0, value, 0, 0.0f, 0.0f, seconds)
#define O101_LINKED_PAIR(t, group, key, x, y, seconds) \
    O101_EVENT(t, O101_EVENT_LINKED_PAIR, group, key, x, y, 0.0f, 0.0f, seconds)
#define O101_LINKED_PAIR2(t, group, key, x, y, seconds) \
    O101_EVENT(t, O101_EVENT_LINKED_PAIR2, group, key, x, y, 0.0f, 0.0f, seconds)
#define O101_LINKED_FLOAT(t, group, key, value, seconds) \
    O101_EVENT(t, O101_EVENT_LINKED_FLOAT, group, key, 0, 0, value, 0.0f, seconds)
#define O101_LINKED_SCALED(t, group, key, value, seconds) \
    O101_EVENT(t, O101_EVENT_LINKED_SCALED, group, key, 0, 0, value, 0.0f, seconds)
#define O101_LINKED_BYTE(t, group, key, value, seconds) \
    O101_EVENT(t, O101_EVENT_LINKED_BYTE, group, key, value, 0, 0.0f, 0.0f, seconds)
#define O101_COLOR_PAIR(first, second) (((first) << 16) | (second))
#define O101_COLOR(t, group, key, red, green, blue, alpha, seconds) \
    O101_EVENT(t, O101_EVENT_COLOR, group, key, \
               O101_COLOR_PAIR(red, green), O101_COLOR_PAIR(blue, alpha), \
               0.0f, 0.0f, seconds)
#define O101_FRAMES(t, group, key, fraction, rate, seconds) \
    O101_EVENT(t, O101_EVENT_FRAMES, group, key, 0, 0, fraction, rate, seconds)
#define O101_GLOBAL_PAIR(t, x, y, seconds) \
    O101_EVENT(t, O101_EVENT_GLOBAL_PAIR, 0, 0, x, y, 0.0f, 0.0f, seconds)
#define O101_FINISH(t) \
    O101_EVENT(t, O101_EVENT_FINISH, 0, 0, 0, 0, 0.0f, 0.0f, 0.0f)
#define O101_SIGNAL(t) \
    O101_EVENT(t, O101_EVENT_SIGNAL, 0, 0, 0, 0, 0.0f, 0.0f, 0.0f)
#define O101_END() \
    O101_EVENT(0.0f, O101_EVENT_END, 0, 0, 0, 0, 0.0f, 0.0f, 0.0f)

