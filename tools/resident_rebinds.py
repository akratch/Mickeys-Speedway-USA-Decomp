#!/usr/bin/env python3
"""The declared resident-call rebinds: mk/overlay_resident_rebinds.generated.mk.

An overlay links at 0xF0000000 and cannot `jal` a 0x8000xxxx entry point, so
adopted C that calls a resident function by its resident name (`fontColour`,
`func_80029120`) must reach it through a per-module placeholder,
`<name>_o<NNN>Reloc`, which `overlay_undefined_syms.us.txt` values at the
stored addend (docs/reloc-surface.md section 5.6).  Most of those renames are
hand-written `--redefine-sym` steps in an object's POSTPROCESS rule.  The rest
used to exist only because `gmake overlay-syms` ran objcopy over the compiled
objects *in place*: nothing in the tree named them, so a fresh build could not
link until overlay-syms had mutated its objects, and any rebuild of one of
those objects (an `--always-make`, a re-extract, an edit to
`symbol_addrs.us.txt`) silently discarded them again.

This module owns the file that replaces that mutation.  `reloc_surface.py
generate` plans the same renames it always derived, and writes them here as
ordinary target-specific Make variables:

    <object>: SURFACE_REBIND = $(OBJCOPY) --redefine-sym a=a_oNNNReloc ... $@

The compile recipe runs `$(SURFACE_REBIND)` after `$(POSTPROCESS)` -- the
order the in-place pass had, since it ran after the whole build -- so every
build of the object, clean or forced, carries the rename, and a clean tree
links in one pass.  mk/overlays.mk makes *every* overlay object depend on this
file, not only the listed ones: an entry that disappears must rebuild its
object without the rename, or the stale object would keep it and the check
below would agree with the edited file.  The rules are generated, never
hand-edited; `gmake check-overlay-syms` fails when the tracked file is not
what the tree generates.

Because a compiled object already carries its declared renames, the planner
reads each object through the *inverse* of its current entry here (`inverse`)
so it sees the names the C spells.  That makes the plan a fixed point of the
file: regenerating after a build reproduces it byte for byte, an entry whose
call disappeared from the source drops out, and a new resident call is
planned whether or not the object has been rebuilt since.

One limit: a rename that a hand-written POSTPROCESS rule later starts doing
as well leaves this file's copy inert (objcopy ignores an absent name), and
the planner cannot tell, because the object looks the same either way.  It
is harmless to the bytes; remove the duplicate from the hand rule.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Mapping

REPO = Path(__file__).resolve().parent.parent
GENERATED_MK = REPO / "mk" / "overlay_resident_rebinds.generated.mk"
GENERATED_MK_REL = "mk/overlay_resident_rebinds.generated.mk"
VARIABLE = "SURFACE_REBIND"
OBJECT_PREFIX = "build/src/overlays/"
MAKE_PREFIX = "$(BUILD_DIR)/$(SRC_DIR)/overlays/"

HEADER = """\
# Generated by tools/reloc_surface.py generate -- do not edit by hand.
# Regenerate with `gmake overlay-syms`; `gmake check-overlay-syms` fails on
# drift.  See tools/resident_rebinds.py and docs/reloc-surface.md section 5.6.
#
# Resident calls that adopted overlay C spells with the resident function's
# own name, renamed to the per-module placeholder that
# overlay_undefined_syms.us.txt values.  The compile recipe applies
# $(SURFACE_REBIND) after $(POSTPROCESS); a hand-written rename in an object's
# POSTPROCESS rule is not repeated here.
"""

_NAME = r"[A-Za-z_][A-Za-z0-9_.$]*"
_VAR_RE = re.compile(
    r"^(?P<target>\S+\.o):\s+%s\s+=\s+\$\(OBJCOPY\)(?P<body>(?:\s+--redefine-sym"
    r"\s+%s=%s)+)\s+\$@$" % (VARIABLE, _NAME, _NAME))
_PAIR_RE = re.compile(r"--redefine-sym\s+(%s)=(%s)" % (_NAME, _NAME))


class RebindFileError(ValueError):
    """The declared-rebind file is not in a form this module wrote."""


def _make_target(obj: str) -> str:
    if not obj.startswith(OBJECT_PREFIX) or not obj.endswith(".o"):
        raise RebindFileError("not an overlay object path: %s" % obj)
    return MAKE_PREFIX + obj[len(OBJECT_PREFIX):]


def _object_path(target: str) -> str:
    if not target.startswith(MAKE_PREFIX):
        raise RebindFileError("rule target is not an overlay object: %s" % target)
    return OBJECT_PREFIX + target[len(MAKE_PREFIX):]


def render(rebinds: Mapping[str, Mapping[str, str]]) -> str:
    """Return the generated file for {object path: {old name: new name}}."""
    blocks = [HEADER]
    for obj in sorted(rebinds):
        pairs = rebinds[obj]
        if not pairs:
            continue
        target = _make_target(obj)
        lines = ["%s: %s = $(OBJCOPY) \\" % (target, VARIABLE)]
        names = sorted(pairs)
        for i, old in enumerate(names):
            tail = " $@" if i == len(names) - 1 else " \\"
            lines.append("\t--redefine-sym %s=%s%s" % (old, pairs[old], tail))
        blocks.append("\n".join(lines) + "\n")
    if len(blocks) == 1:
        blocks.append("# No overlay object currently needs one.\n")
    return "\n".join(blocks)


def parse(text: str) -> dict[str, dict[str, str]]:
    """Read back {object path: {old: new}}; refuse anything unrecognized.

    Deliberately accepts a file that is merely out of order (a clean merge of
    two lanes' additions), because the planner needs its contents to undo the
    renames compiled objects already carry; `--check` is what insists on the
    exact generated text.
    """
    out: dict[str, dict[str, str]] = {}
    logical = text.replace("\\\n", " ")
    for raw in logical.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = _VAR_RE.match(line)
        if m:
            obj = _object_path(m.group("target"))
            if obj in out:
                raise RebindFileError("two %s rules for %s" % (VARIABLE, obj))
            pairs: dict[str, str] = {}
            for old, new in _PAIR_RE.findall(m.group("body")):
                if old in pairs:
                    raise RebindFileError("%s renames %s twice" % (obj, old))
                pairs[old] = new
            out[obj] = pairs
            continue
        raise RebindFileError("unrecognized line in %s: %s"
                              % (GENERATED_MK_REL, line[:120]))
    return out


def read(path: Path = GENERATED_MK) -> dict[str, dict[str, str]]:
    """The declared rebinds, or {} when the file does not exist yet."""
    if not path.is_file():
        return {}
    try:
        return parse(path.read_text())
    except RebindFileError as error:
        raise SystemExit("%s: %s; restore it with `git checkout -- %s` and "
                         "rerun `gmake overlay-syms`"
                         % (path.name, error, GENERATED_MK_REL))


def inverse(pairs: Mapping[str, str]) -> dict[str, str]:
    """{new: old} for one object's declared renames."""
    return {new: old for old, new in pairs.items()}


def write_if_changed(path: Path, text: str) -> bool:
    """Write only on a content change, so unchanged rules rebuild nothing."""
    if path.is_file() and path.read_text() == text:
        return False
    path.write_text(text)
    return True
