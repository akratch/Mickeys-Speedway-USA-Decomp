#!/usr/bin/env python3
"""Resident overlay calls and callbacks: named in C, trapped in the object.

Mickey's resident code reaches a function in a not-yet-loaded overlay through
a `jal TrapDanglingJump`; the shipped main relocation table names, per call
site, the `overlayRomTable` row that says which overlay export that site
really calls (docs/overlays.md section 5.1). The C therefore calls the real
overlay function by name, declared in `include/game/overlay_exports.h`, and
this tool renames those undefined references to `TrapDanglingJump` in the
compiled resident object before it is linked -- the arrangement Jet Force
Gemini's decomp uses (its `tools/patch_symbols.py` and
`ver/symbols/overlay_funcs_to_trap.txt`). Nothing but symbol names changes, so
the instruction words, relocation offsets and types, and the linked ROM are
the bytes a literal `TrapDanglingJump(...)` call produced.

Three subcommands:

  rename OBJECT LIST   The per-object POSTPROCESS step (Makefile, every
                       resident C object). Renames each undefined symbol LIST
                       names to TrapDanglingJump and writes OBJECT.trapsites,
                       which records the C-level name at every renamed
                       `.text` relocation or zero-addend `.data` callback.
                       Fail-closed: a listed name the
                       object *defines*, a listed name used by anything but an
                       R_MIPS_26 `.text` or R_MIPS_32 `.data` relocation, and an undefined symbol
                       spelled like an overlay export but missing from LIST
                       are all errors.

  generate [--write]   Derive LIST from the shipped tables and the linked
                       overlay symbol names: every main relocation record
                       whose call-site word is `jal TrapDanglingJump`,
                       through its overlayRomTable row to (overlay, offset),
                       to the overlay function defined there. The function's
                       friendly name when it has exactly one, else its
                       canonical `func_overlay_NNN_...` name. Without
                       --write it fails when LIST is stale.

  check                The semantic proof, run by `gmake verify` after the
                       ROM hash matches: every shipped trap site lies in a
                       resident C object whose fresh sidecar names, at that
                       site, a function the site's ORT row targets; no
                       resident C object calls TrapDanglingJump literally;
                       LIST equals the generated list; and the site's ORT
                       target agrees with config/overlays.us.json's
                       `resident_inbound` row. Sites in assembly objects are
                       counted, not failed.

LIST is tracked (config/overlay_funcs_to_trap.us.txt) and holds names only.
The site-level mapping, which carries addresses, exists only at run time and
under build/.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import struct
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "tools"))

TRAP = "TrapDanglingJump"
SIDECAR_SUFFIX = ".trapsites"
SIDECAR_FORMAT = 1

SHT_SYMTAB = 2
SHT_RELA = 4
SHT_NOBITS = 8
SHT_REL = 9
STT_FUNC = 2
STB_GLOBAL, STB_WEAK = 1, 2
R_MIPS_32, R_MIPS_26 = 2, 4

OVERLAY_VMA = 0xF0000000

# Undefined resident references spelled like an overlay export. A name the
# list does not carry is refused rather than left for the linker, where it
# surfaces as an R_MIPS_26 overflow that names neither the cause nor the fix.
OVERLAY_EXPORT_SPELLING = re.compile(r"^(func_overlay_\d{3}_\w+|overlay\d+[A-Z]\w*)$")

DEFAULT_LIST = REPO / "config" / "overlay_funcs_to_trap.us.txt"
DEFAULT_ATLAS = REPO / "config" / "overlays.us.json"
DEFAULT_ELF = REPO / "build" / "mickey.us.elf"
DEFAULT_ROM = REPO / "build" / "mickey.us.z64"
DEFAULT_BASEROM = REPO / "baseroms" / "mickey.us.z64"
DEFAULT_MAP = REPO / "build" / "mickey.us.map"
RESIDENT_C_OBJECT = re.compile(r"^build/src/main/[^/]+\.c\.o$")

LIST_HEADER = """\
# Overlay exports that resident C calls or stores as callbacks by name.
#
# Generated by `gmake trap-names` (tools/trap_names.py generate --write) from
# the shipped main relocation table, overlayRomTable and the linked overlay
# symbol names; `gmake verify` fails when it is stale. Each resident object's
# undefined references to these names are renamed to TrapDanglingJump before
# the link, so the C names the callee and ordinary relocation supplies the
# trap call or callback initializer. Callback receipts bind the entire object
# and its R32 inventory, since an unrelocated NULL has the same raw zero word.
# Names only. See docs/overlays.md section 5.1.
"""


class TrapError(RuntimeError):
    """A fail-closed refusal; the message says what to fix."""


# --------------------------------------------------------------------------
# ELF32 big-endian primitives


def _sections(data: bytes) -> list[tuple[str, tuple[int, ...]]]:
    if data[:6] != b"\x7fELF\x01\x02":
        raise TrapError("expected a big-endian ELF32 object")
    shoff = struct.unpack_from(">I", data, 0x20)[0]
    shentsize, shnum, shstrndx = struct.unpack_from(">HHH", data, 0x2E)
    if shentsize < 40 or shstrndx >= shnum or shoff + shnum * shentsize > len(data):
        raise TrapError("malformed ELF section table")
    headers = [struct.unpack_from(">10I", data, shoff + i * shentsize) for i in range(shnum)]
    names = _strings(data, headers[shstrndx])
    return [(_c_string(names, h[0]), h) for h in headers]


def _strings(data: bytes, header: tuple[int, ...]) -> bytes:
    start, size = header[4], header[5]
    if start + size > len(data):
        raise TrapError("string table extends past end of file")
    return data[start:start + size]


def _c_string(blob: bytes, offset: int) -> str:
    end = blob.find(b"\0", offset)
    if offset >= len(blob) or end < 0:
        raise TrapError(f"bad string offset {offset:#x}")
    return blob[offset:end].decode("ascii")


def _symbols(data: bytes, sections, index: int) -> list[dict]:
    _name, header = sections[index]
    strings = _strings(data, sections[header[6]][1])
    entry = header[9] or 16
    out = []
    for number, offset in enumerate(range(header[4], header[4] + header[5], entry)):
        st_name, value, size, info, _other, shndx = struct.unpack_from(">IIIBBH", data, offset)
        out.append({"index": number, "entry": offset, "name": _c_string(strings, st_name),
                    "value": value, "size": size, "bind": info >> 4, "type": info & 15,
                    "shndx": shndx})
    return out


def _single_symtab(sections) -> int:
    tables = [i for i, (_n, h) in enumerate(sections) if h[1] == SHT_SYMTAB]
    if len(tables) != 1:
        raise TrapError(f"expected one symbol table, found {len(tables)}")
    return tables[0]


def _relocations(data: bytes, sections, symtab: int):
    """Yield (target section name, offset, type, symbol index) for every record."""
    for _name, header in sections:
        if header[1] not in (SHT_REL, SHT_RELA) or header[6] != symtab:
            continue
        target = sections[header[7]][0]
        entry = header[9] or (8 if header[1] == SHT_REL else 12)
        for offset in range(header[4], header[4] + header[5], entry):
            r_offset, info = struct.unpack_from(">II", data, offset)
            yield target, r_offset, info & 0xFF, info >> 8


def _section_bytes(data: bytes, sections, name: str) -> bytes:
    for section, header in sections:
        if section == name:
            return b"" if header[1] == SHT_NOBITS else data[header[4]:header[4] + header[5]]
    return b""


# --------------------------------------------------------------------------
# rename


def load_names(path: Path) -> list[str]:
    names = []
    for line in path.read_text(encoding="ascii").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        if not re.fullmatch(r"[A-Za-z_]\w*", line):
            raise TrapError(f"{path}: not a symbol name: {line!r}")
        names.append(line)
    if len(set(names)) != len(names):
        raise TrapError(f"{path}: duplicate names")
    return names


def rename_object(data: bytes, names: set[str]) -> tuple[bytes, dict]:
    """Rename undefined references to `names`; return (new bytes, sidecar record)."""
    sections = _sections(data)
    symtab = _single_symtab(sections)
    symbols = _symbols(data, sections, symtab)

    defined = sorted({s["name"] for s in symbols if s["name"] in names and s["shndx"] != 0})
    if defined:
        raise TrapError("defines listed overlay export(s), which a resident object must "
                        "not: " + ", ".join(defined))
    unknown = sorted({s["name"] for s in symbols if s["shndx"] == 0 and s["name"] not in names
                      and OVERLAY_EXPORT_SPELLING.match(s["name"])})
    if unknown:
        raise TrapError("references overlay export(s) the trap list does not name: "
                        + ", ".join(unknown) + " (regenerate the list with `gmake trap-names`, "
                        "or call the name the ORT row targets)")
    targets = {s["index"]: s["name"] for s in symbols if s["shndx"] == 0 and s["name"] in names}
    if targets and any(s["name"] == TRAP and s["shndx"] != 0 for s in symbols):
        raise TrapError(f"defines {TRAP} and also references listed names")

    sites, literal, data_sites, data_literal = [], [], [], []
    for target, offset, rtype, index in _relocations(data, sections, symtab):
        if index in targets:
            if target == ".text" and rtype == R_MIPS_26:
                sites.append({"offset": offset, "name": targets[index]})
            elif target == ".data" and rtype == R_MIPS_32:
                payload = _section_bytes(data, sections, ".data")
                if (offset % 4 or offset < 0 or offset + 4 > len(payload)
                        or struct.unpack_from(">I", payload, offset)[0] != 0):
                    raise TrapError("callback initializer requires a bounded zero-addend .data R32")
                data_sites.append({"offset": offset, "name": targets[index]})
            else:
                raise TrapError(f"{targets[index]} is referenced by a type-{rtype} relocation "
                                f"in {target}; only a .text jal or .data R32 callback can trap")
        elif symbols[index]["name"] == TRAP and target == ".text" and rtype == R_MIPS_26:
            literal.append(offset)
        elif symbols[index]["name"] == TRAP and target == ".data":
            data_literal.append(offset)

    out = bytearray(data)
    if targets:
        strtab_index = sections[symtab][1][6]
        strtab = _strings(data, sections[strtab_index][1])
        needle = TRAP.encode("ascii") + b"\0"
        found = strtab.find(b"\0" + needle)
        if found >= 0:
            at = found + 1
        else:
            # Append a copy of the string table that also holds the name; the
            # original bytes stay where they are, unreferenced.
            new_offset = (len(out) + 3) & ~3
            out.extend(b"\0" * (new_offset - len(out)))
            at = len(strtab)
            out.extend(strtab + needle)
            shoff = struct.unpack_from(">I", data, 0x20)[0]
            shentsize = struct.unpack_from(">H", data, 0x2E)[0]
            header = shoff + strtab_index * shentsize
            struct.pack_into(">II", out, header + 0x10, new_offset, len(strtab) + len(needle))
        for index in targets:
            struct.pack_into(">I", out, symbols[index]["entry"], at)

    text = _section_bytes(bytes(out), _sections(bytes(out)), ".text")
    record = {
        "format": SIDECAR_FORMAT,
        "text_sha256": hashlib.sha256(text).hexdigest(),
        "sites": sorted(sites, key=lambda row: row["offset"]),
        "literal": sorted(literal),
    }
    if data_sites or data_literal:
        record.update(format=2, object_sha256=hashlib.sha256(out).hexdigest(),
                      data_sha256=hashlib.sha256(_section_bytes(bytes(out), _sections(bytes(out)), ".data")).hexdigest(),
                      data_sites=sorted(data_sites, key=lambda row: row["offset"]),
                      data_literal=sorted(data_literal))
        # Share the final consumer's full-object/relocation contract. Nothing
        # in the initializer or its relocation table is patched here.
        import runlink_pack as rp
        try:
            rp.resident_data_callees(rp.Elf("resident object", data=bytes(out)), record)
        except rp.PackError as error:
            raise TrapError(str(error)) from error
    return bytes(out), record


def _atomic_write(path: Path, payload: bytes) -> None:
    """Replace `path`, keeping its mode (mkstemp's 0600 otherwise sticks)."""
    try:
        mode = path.stat().st_mode & 0o777
    except OSError:
        umask = os.umask(0)
        os.umask(umask)
        mode = 0o666 & ~umask
    handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".")
    try:
        with os.fdopen(handle, "wb") as stream:
            stream.write(payload)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    except BaseException:
        if os.path.exists(temporary):
            os.unlink(temporary)
        raise


def command_rename(args) -> int:
    obj = Path(args.object)
    names = set(load_names(Path(args.list)))
    try:
        new, record = rename_object(obj.read_bytes(), names)
    except TrapError as error:
        print(f"trap_names.py rename: {obj}: {error}", file=sys.stderr)
        return 1
    sidecar = Path(str(obj) + SIDECAR_SUFFIX)
    if not record["sites"] and not record.get("data_sites") and _already_renamed(sidecar, record):
        return 0
    if new != obj.read_bytes():
        _atomic_write(obj, new)
    _atomic_write(sidecar, (json.dumps(record, indent=1, sort_keys=True) + "\n").encode())
    return 0


def _already_renamed(sidecar: Path, record: dict) -> bool:
    """A second run over a renamed object keeps the sidecar the first run wrote."""
    try:
        previous = json.loads(sidecar.read_text())
    except (OSError, ValueError):
        return False
    if previous.get("format") == 2:
        return (bool(previous.get("sites") or previous.get("data_sites"))
                and previous.get("object_sha256") == record.get("object_sha256")
                and previous.get("data_sha256") == record.get("data_sha256")
                and previous.get("text_sha256") == record.get("text_sha256")
                and {row["offset"] for row in previous["sites"]} | set(previous["literal"]) == set(record["literal"])
                and {row["offset"] for row in previous["data_sites"]} | set(previous["data_literal"]) == set(record.get("data_literal", [])))
    return (previous.get("format") == SIDECAR_FORMAT and bool(previous.get("sites"))
            and previous.get("text_sha256") == record["text_sha256"]
            and {row["offset"] for row in previous["sites"]} <= set(record["literal"]))


